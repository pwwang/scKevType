"""Deterministic synthetic fixtures for the smoke corpus — generated, never downloaded.

    python configs/corpus/fixtures/smoke/generate.py

Two tiny datasets, one per file layout the factory reads:

* ``data/tenx_blood/`` — a 10x bundle (``matrix.mtx`` + barcodes + features) with the
  silver-standard ``labels.tsv`` the 10x adapter insists on;
* ``data/cellxgene_lung.h5ad`` — CELLxGENE-shaped: ``obs`` holds CL ids, a donor and a
  tissue, ``var/_index`` holds Ensembl-style ids with the symbols in ``feature_name``,
  and ``X`` is a CSR group.

They are synthetic, so the smoke config marks both ``registered: false`` under ids
that are not in the registry: a fixture that merely *looks* like pbmc3k must never be
recorded as pbmc3k.

Gene panels are read from the frozen definitions (``artifacts/v1``) rather than
listed here: a fixture that drifts from the definitions would quietly stop
exercising the renderer, and which markers a type has is the artifact's business.

Expression is a pure function of the cell's index, so the generated bytes are
reproducible without an RNG and ``--check`` can diff against what is committed.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import h5py
import numpy as np

ROOT = Path(__file__).resolve().parents[4]
ARTIFACTS = ROOT / "artifacts" / "v1"
HERE = Path(__file__).resolve().parent

#: The datasets, and which types they hold. One unmappable label per dataset, so the
#: recorded drop count in ``qc.json`` is a number with something in it.
TENX_DONORS = ("d1", "d2", "d3", "d4", "d5")
TENX_TYPES = ("CL:0000624", "CL:0000623", "CL:0000236", "CL:0000860", "CL:0000233", "Doublet")
H5AD_DONORS = ("a", "b", "c", "d", "e", "f")
H5AD_TYPES = ("CL:0000084", "CL:0000623", "CL:0000235", "CL:0000066", "CL:9999999")
CELLS_PER_DONOR = 3

#: Genes no definition names, so the corpus's ``de_markers`` (and thus the leakage
#: guard) has something to look at.
EXTRA_GENES = ("CTSS", "SAT1")


def _definitions() -> dict[str, dict]:
    payload = json.loads((ARTIFACTS / "definitions.json").read_text(encoding="utf-8"))
    return {entry["cl_id"]: entry for entry in payload["definitions"]}


def _ubiquitous() -> tuple[str, ...]:
    config = json.loads((ARTIFACTS / "render_config.json").read_text(encoding="utf-8"))
    return tuple(config["ubiquitous"])


def _universe(types: tuple[str, ...], definitions: dict[str, dict], ubiquitous: tuple[str, ...]) -> list[str]:
    """Every gene the fixture expresses, in a fixed order: markers, then housekeeping."""
    symbols: list[str] = []
    for cl_id in types:
        # The unmappable label of each fixture has no definition and expresses nothing
        # but housekeeping — which is what makes it a label the label map drops.
        for marker in definitions.get(cl_id, {}).get("pos_markers", []) + definitions.get(cl_id, {}).get("neg_markers", []):
            if marker not in symbols:
                symbols.append(marker)
    return symbols + [gene for gene in (*ubiquitous, *EXTRA_GENES) if gene not in symbols]


def _expression(cl_id: str, index: int, universe: list[str], definitions: dict[str, dict], ubiquitous: tuple[str, ...]) -> dict[str, float]:
    """One cell's non-zero genes: its type's markers, housekeeping, and a little noise.

    Only *positive* markers are expressed. A synthetic cell that also carried its
    definition's negative markers would satisfy no definition at all (``HoldsRule``
    allows none), and every ``marker_noul`` answer in the smoke corpus would be
    ``false`` — a fixture that cannot tell the two answers apart.

    The rank order matters too — positive markers sit *below* the housekeeping genes,
    which the renderer filters out, so the smoke corpus exercises the filter rather
    than feeding the model a state that is already the answer.
    """
    definition = definitions.get(cl_id, {"pos_markers": [], "neg_markers": []})
    expressed: dict[str, float] = {}
    for position, marker in enumerate(definition["pos_markers"]):
        expressed[marker] = 2.0 + (index % 3) + (position % 2)
    for marker in ubiquitous:
        expressed[marker] = 6.0
    for position, marker in enumerate(EXTRA_GENES):
        expressed[marker] = 1.0 + ((index + position) % 2)
    return {gene: expressed[gene] for gene in universe if gene in expressed}


def write_tenx(directory: Path) -> None:
    """``matrix.mtx`` + barcodes + features + a silver-standard ``labels.tsv``."""
    definitions, ubiquitous = _definitions(), _ubiquitous()
    universe = _universe(TENX_TYPES, definitions, ubiquitous)
    barcodes, labels, rows = [], [], []
    for donor_index, donor in enumerate(TENX_DONORS):
        for offset in range(CELLS_PER_DONOR):
            cl_id = TENX_TYPES[(donor_index + offset) % len(TENX_TYPES)]
            index = len(barcodes)
            barcodes.append(f"{donor}_cell{offset}")
            labels.append((barcodes[-1], cl_id if cl_id in definitions else "Doublet"))
            rows.append(_expression(cl_id, index, universe, definitions, ubiquitous))
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "barcodes.tsv").write_text("".join(f"{barcode}\n" for barcode in barcodes), encoding="utf-8")
    (directory / "features.tsv").write_text(
        "".join(f"ENSG{position:011d}\t{gene}\tGene Expression\n" for position, gene in enumerate(universe)), encoding="utf-8"
    )
    (directory / "labels.tsv").write_text("".join(f"{barcode}\t{label}\n" for barcode, label in labels), encoding="utf-8")
    entries = [
        (universe.index(gene) + 1, cell + 1, value)
        for cell, row in enumerate(rows)
        for gene, value in sorted(row.items(), key=lambda item: universe.index(item[0]))
    ]
    entries.sort(key=lambda entry: (entry[1], entry[0]))
    body = [
        "%%MatrixMarket matrix coordinate integer general",
        "%",
        f"{len(universe)} {len(barcodes)} {len(entries)}",
        *(f"{gene} {cell} {value:g}" for gene, cell, value in entries),
    ]
    (directory / "matrix.mtx").write_text("\n".join(body) + "\n", encoding="utf-8")


def write_h5ad(path: Path) -> None:
    """A CELLxGENE-shaped h5ad: CL ids in ``obs``, symbols in ``var/feature_name``, CSR ``X``."""
    definitions, ubiquitous = _definitions(), _ubiquitous()
    universe = _universe(H5AD_TYPES, definitions, ubiquitous)
    cell_ids, types, donors, rows = [], [], [], []
    for donor in H5AD_DONORS:
        for offset in range(CELLS_PER_DONOR + 1):
            cl_id = H5AD_TYPES[(H5AD_DONORS.index(donor) + offset) % len(H5AD_TYPES)]
            cell_ids.append(f"{donor}-{offset}")
            types.append(cl_id)
            donors.append(donor)
            rows.append(_expression(cl_id, len(cell_ids) - 1, universe, definitions, ubiquitous))
    data, indices, indptr = [], [], [0]
    for row in rows:
        for gene, value in sorted(row.items(), key=lambda item: universe.index(item[0])):
            indices.append(universe.index(gene))
            data.append(value)
        indptr.append(len(indices))
    path.parent.mkdir(parents=True, exist_ok=True)
    with h5py.File(path, "w") as handle:
        obs = handle.create_group("obs")
        obs.create_dataset("_index", data=np.array(cell_ids, dtype=object), dtype=h5py.string_dtype())
        # A plain string column and a categorical one, because a real h5ad has both and
        # the adapter has to read either (categories + codes, -1 for missing).
        obs.create_dataset("cell_type_ontology_term_id", data=np.array(types, dtype=object), dtype=h5py.string_dtype())
        obs.create_dataset("tissue_ontology_term_id", data=np.array(["UBERON:0002048"] * len(cell_ids), dtype=object), dtype=h5py.string_dtype())
        categorical = obs.create_group("donor_id")
        unique = sorted(set(donors))
        categorical.create_dataset("categories", data=np.array(unique, dtype=object), dtype=h5py.string_dtype())
        categorical.create_dataset("codes", data=np.array([unique.index(donor) for donor in donors], dtype=np.int32))
        var = handle.create_group("var")
        var.create_dataset("_index", data=np.array([f"ENSG{position:011d}" for position in range(len(universe))], dtype=object), dtype=h5py.string_dtype())
        var.create_dataset("feature_name", data=np.array(universe, dtype=object), dtype=h5py.string_dtype())
        matrix = handle.create_group("X")
        matrix.attrs["encoding-type"] = "csr_matrix"
        matrix.attrs["shape"] = np.array([len(cell_ids), len(universe)], dtype=np.int64)
        matrix.create_dataset("data", data=np.array(data, dtype=np.float32))
        matrix.create_dataset("indices", data=np.array(indices, dtype=np.int32))
        matrix.create_dataset("indptr", data=np.array(indptr, dtype=np.int64))


def generate(root: Path = HERE / "data") -> list[Path]:
    """(Re)generate both fixtures under ``root``; return the paths written."""
    write_tenx(root / "tenx_blood")
    write_h5ad(root / "cellxgene_lung.h5ad")
    return sorted(path for path in root.rglob("*") if path.is_file())


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="fixtures.smoke.generate", description=__doc__.splitlines()[0])
    parser.add_argument("--out", default=str(HERE / "data"), help="directory to write the fixtures into")
    parser.add_argument("--check", action="store_true", help="verify the committed fixtures are current instead of writing")
    args = parser.parse_args(argv)
    root = Path(args.out)
    before = {path: path.read_bytes() for path in sorted(root.rglob("*")) if path.is_file()}
    written = generate(root)
    if not args.check:
        for path in written:
            print(path.relative_to(root.parent))
        return 0
    after = {path: path.read_bytes() for path in written}
    stale = sorted(str(path.relative_to(root.parent)) for path in set(before) | set(after) if before.get(path) != after.get(path))
    if stale:
        print(f"stale fixtures (re-run generate.py): {stale}", file=sys.stderr)
        return 1
    print(f"{len(after)} fixture files up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
