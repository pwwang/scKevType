# --------------------------------------------------------------------------- registry


def load_registry(path: str | Path | None = None) -> dict[str, dict[str, Any]]:
    """The model registry, refusing an entry that pins no revision."""
    import yaml

    config = Path(path) if path else paths.configs_dir() / "models.yaml"
    models = (yaml.safe_load(config.read_text(encoding="utf-8")) or {}).get("models") or {}
    for key, entry in models.items():
        if not entry.get("revision"):
            raise ValueError(f"models.yaml: {key!r} pins no revision — an unpinned base cannot be measured")
    if not models:
        raise ValueError(f"models.yaml: no models registered at {config}")
    return models


def cached(entry: dict[str, Any]) -> bool:
    """Whether the base's weights are already on disk, so measuring cannot fetch them."""
    from huggingface_hub import scan_cache_dir

    return any(repo.repo_id == entry["id"] for repo in scan_cache_dir().repos)


# --------------------------------------------------------------------------- data


def row_shape(model: Any, enc: dict) -> tuple[int, int]:
    """``(rows, tokens)`` for one encoding: how many questions, and what they cost the backbone."""
    if not model.rows_form([enc]):
        return 1, len(enc["ids"])
    from kev.model import rows_of

    state, _, rows = rows_of(enc)
    return len(rows), sum(len(state) + len(row["ids"]) for row in rows)


def encode_records(model: Any, tokenizer: Any, records: list[dict[str, Any]], max_state: int) -> list[Any]:
    """Encode records strictly and *without* augmentation, so a batch is the same bytes every time."""
    import kev.train as kt
    from kev.model import training_context

    limits = training_context(max_state)
    out = []
    for record in records:
        materialized = kt.materialize(record)
        enc = model.encode(tokenizer, materialized, strict=True,
                           max_state=limits["max_state"], max_branch=limits["max_branch"])
        out.append(kt.Variant(materialized, enc, record["_meta"]["id"], record["_meta"]["source"]))
    return out


def take_batch(model: Any, variants: list[Any], batch: int) -> list[Any]:
    """The ``batch`` longest rows, so batch sizes nest and peak memory is comparable across them.

    Deterministic on purpose: the same suite and the same batch size must select
    the same records on every run, or the table is not reproducible.
    """
    ranked = sorted(variants, key=lambda variant: (-forward_tokens(model, variant.enc), variant.request_id))
    return ranked[:batch]


# --------------------------------------------------------------------------- measurement


def measure(model: Any, variants: list[Any], ns: Any, batch: int, args: argparse.Namespace,
            checkpointing: int) -> dict[str, Any]:
    """Time and size one (batch size, checkpointing) combination on the frozen model."""
    import kev.train as kt
    import torch
    from kev.device import allocated_bytes, empty_cache, sync

    chunk = take_batch(model, variants, batch)
    shapes = [row_shape(model, variant.enc) for variant in chunk]
    tokens = sum(row_tokens(model, variant.enc) for variant in chunk)
    record: dict[str, Any] = {
        "batch": len(chunk), "rows": sum(rows for rows, _ in shapes), "row_tokens": tokens,
        "median_row_tokens": int(statistics.median(tokens_ for _, tokens_ in shapes)),
        "checkpointing": checkpointing, "warmup_steps": args.warmup, "timed_steps": args.steps,
    }

    if checkpointing:
        model.lm.gradient_checkpointing_enable(gradient_checkpointing_kwargs={"use_reentrant": False})
    else:
        model.lm.gradient_checkpointing_disable()
    empty_cache(args.device)
    if args.device == "cuda":
        torch.cuda.reset_peak_memory_stats()

    autocast = torch.autocast("cuda", dtype=torch.bfloat16) if args.dtype == "bf16" else contextlib.nullcontext()
    optimizer = torch.optim.AdamW(list(model.trainable_parameters()), lr=1e-6)
    seconds, peaks = [], []
    try:
        for index in range(args.warmup + args.steps):
            if args.device == "cuda":
                torch.cuda.reset_peak_memory_stats()
            sync(args.device)
            started = time.perf_counter()
            loss, _ = kt.batch_loss(model, ns, chunk, args.device, {}, None, autocast)
            loss.backward()
            optimizer.step()
            optimizer.zero_grad(set_to_none=True)
            sync(args.device)
            elapsed = time.perf_counter() - started
            if index == 0:
                record["cold_step_seconds"] = elapsed
            if index >= args.warmup:
                seconds.append(elapsed)
                peaks.append(allocated_bytes(args.device))
    except torch.cuda.OutOfMemoryError as error:
        optimizer.zero_grad(set_to_none=True)
        if args.device == "cuda":
            torch.cuda.empty_cache()
        return record | {"status": OOM, "detail": str(error).splitlines()[0]}

    return record | {
        "status": "ok",
        "step_seconds": statistics.median(seconds),
        "step_seconds_min": min(seconds),
        "step_seconds_max": max(seconds),
        "tokens_per_second": tokens / statistics.median(seconds),
        "peak_device_bytes": max(peaks),
    }


def row_tokens(model: Any, enc: dict) -> int:
    """The rerun-safe wrapper: ``forward_tokens`` needs the model only for its row-form decision."""
    return forward_tokens(model, enc)


def measure_model(key: str, entry: dict[str, Any], args: argparse.Namespace, registry_keys: list[str]) -> dict[str, Any]:
    """Build, verify and measure one registry entry."""
    import kev.train as kt
    import torch
    from kev.model import load_tokenizer

    from . import model as model_module

    row: dict[str, Any] = {"key": key, **entry, "status": "ok", "combinations": []}
    if not cached(entry):
        row["status"] = f"not in the local hub cache, and this command does not fetch ({', '.join(registry_keys)} were asked for)"
        return row

    tokenizer = load_tokenizer(entry["id"], revision=entry["revision"])
    built = model_module.build_model(entry["id"], entry["revision"], {}, device=args.device, tokenizer=tokenizer)
    trainables = model_module.verify_frozen(built)
    built.train()
    built.lm.config.use_cache = False
    variants = encode_records(built, tokenizer, kt.load_split(args.suite, "train"), args.max_state)

    row |= {
        "text_only": True,
        "parameters": sum(parameter.numel() for parameter in built.parameters()),
        "vision_parameters": sum(parameter.numel() for name, parameter in built.named_parameters()
                                 if any(part in model_module.VISION_PREFIXES for part in name.split("."))),
        "hidden_size": getattr(built.lm.config, "hidden_size", None),
        "unfrozen_backbone_tensors": len([name for name in trainables.names
                                          if model_module._kind(name) == model_module.BACKBONE]),
        "trainable": {"count": trainables.count, "by_kind": trainables.by_kind},
        "records": len(variants),
        "suite_row_tokens": sum(row_tokens(built, variant.enc) for variant in variants),
    }
    print(f"{key}: {trainables} — {args.batches} × checkpointing {args.checkpointing}", file=sys.stderr, flush=True)

    namespace = _namespace(args)
    for checkpointing in args.checkpointing_settings:
        for batch in args.batch_sizes:
            if batch > len(variants):
                print(f"  batch {batch}: skipped, the suite has {len(variants)} records", file=sys.stderr, flush=True)
                continue
            print(f"  batch {batch} ckpt {checkpointing}: {args.warmup} warmup + {args.steps} timed",
                  file=sys.stderr, flush=True)
            result = measure(built, variants, namespace, batch, args, checkpointing)
            row["combinations"].append(result | {"model": key})
            print(f"    -> {result['status']}"
                  + (f" {result['step_seconds']:.3f} s/step {result['tokens_per_second']:,.0f} tok/s "
                     f"{result['peak_device_bytes'] / 2**30:.2f} GB" if result["status"] == "ok" else ""),
                  file=sys.stderr, flush=True)
    del built, tokenizer, variants
    if args.device == "cuda":
        torch.cuda.empty_cache()
    return row


def _namespace(args: argparse.Namespace) -> Any:
    """``kev.train``'s defaults with this run's dtype, so the loss is the trainer's own."""
    from .model import kev_defaults

    namespace = argparse.Namespace(**kev_defaults())
    namespace.dtype = args.dtype
    return namespace


# --------------------------------------------------------------------------- the document


def _gb(value: float | None) -> str:
    return "—" if value is None else f"{value / 2**30:.2f}"


def _mb_per_token(entry: dict[str, Any]) -> float:
    """The peak of one measurement divided by the tokens it paid for — what the trade is priced at."""
    return entry["peak_device_bytes"] / entry["row_tokens"] / 2**20


def _forecast(entry: dict[str, Any], tokens: int) -> float:
    """What a batch of ``tokens`` row tokens would peak at, at ``entry``'s measured slope, in GB."""
    return _mb_per_token(entry) * tokens / 1024


def _gpu_memory() -> float | None:
    """This card's capacity in bytes, so a peak can be read against the thing it has to fit in."""
    import torch

    return torch.cuda.get_device_properties(0).total_memory if torch.cuda.is_available() else None


def _kinds(by_kind: dict[str, int]) -> str:
    return ", ".join(f"{kind} {size:,}" for kind, size in sorted(by_kind.items()) if size)


