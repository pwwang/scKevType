def _probe(rows: list[dict[str, Any]]) -> dict[str, Any]:
    measured = [row for row in rows if row["status"] == "ok"]
    return measured[0] if measured else {}


def table(rows: list[dict[str, Any]]) -> list[str]:
    """The sweep: one row per (model, batch, row tokens, checkpointing)."""
    lines = [
        "## The sweep",
        "",
        "| model | batch | rows | row tokens | median row | checkpointing | s/step | tokens/s | peak VRAM | MB per row token |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        if row["status"] != "ok":
            continue
        for entry in row["combinations"]:
            if entry["status"] != "ok":
                lines.append(f"| {row['key']} | {entry['batch']} | {entry['rows']} | {entry['row_tokens']:,} | "
                             f"{entry['median_row_tokens']} | {entry['checkpointing']} | — | — | **{OOM}** | — |")
                continue
            lines.append(
                f"| {row['key']} | {entry['batch']} | {entry['rows']} | {entry['row_tokens']:,} | "
                f"{entry['median_row_tokens']} | {entry['checkpointing']} | {entry['step_seconds']:.3f} | "
                f"{entry['tokens_per_second']:,.0f} | {_gb(entry['peak_device_bytes'])} GB | "
                f"{entry['peak_device_bytes'] / entry['row_tokens'] / 2**20:.2f} |"
            )
    lines += [
        "",
        "`rows` counts questions; `row tokens` counts what the backbone actually sees. The hybrid",
        "backbone runs one causal row per question, each repeating the state, so the packed length",
        "would undercount the real work by roughly the question count.",
        "",
    ]
    return lines


def warmup_note(rows: list[dict[str, Any]]) -> list[str]:
    """The cold-clock evidence: the first step of a process against the warm median."""
    cold = [entry for row in rows if row["status"] == "ok" for entry in row["combinations"]
            if entry.get("cold_step_seconds") and entry.get("step_seconds")]
    if not cold:
        return []
    entry = max(cold, key=lambda item: item["cold_step_seconds"] / item["step_seconds"])
    ratio = entry["cold_step_seconds"] / entry["step_seconds"]
    return [
        "### Why the warmup is not optional",
        "",
        f"Coldest reading: `{entry['model']}` batch {entry['batch']}, checkpointing {entry['checkpointing']} — the",
        f"first step of the process took **{entry['cold_step_seconds']:.3f} s** against a warm median of",
        f"**{entry['step_seconds']:.3f} s**, a factor of **{ratio:.1f}×**. Every combination above is timed",
        f"after {entry['warmup_steps']} discarded steps; without them the table would be off by that factor.",
        "",
    ]


def anomaly(rows: list[dict[str, Any]]) -> list[str]:
    """The 19.6 GB question, answered from the measurements above rather than from the spec."""
    measured = [entry for row in rows if row["status"] == "ok" for entry in row["combinations"]
                if entry["status"] == "ok"]
    lines = [
        "## The 19.6 GB anomaly",
        "",
        f"The specification records a probe at batch {PROBE['batch']} × seq {PROBE['seq']:,} on the 0.8B text model",
        (f"with grad-checkpointing: {PROBE['tokens_per_second']:,} tok/s, {PROBE['step_seconds']} s/step, "
         f"**{PROBE['peak_gb']} GB peak**,"),
        "and calls that too high for a LoRA-only 0.8B — a live suspect for an unfrozen backbone. That is",
        "testable, so it was tested.",
        "",
    ]
    for row in rows:
        if row["status"] != "ok":
            continue
        lines += [
            f"**The backbone is frozen.** `{row['key']}` builds to {row['parameters']:,} parameters, of which",
            f"{row['trainable']['count']:,} require grad — {_kinds(row['trainable']['by_kind'])}. Backbone tensors",
            f"requiring grad: **{row['unfrozen_backbone_tensors']}**. `verify_frozen` raises rather than letting a run",
            "start otherwise, so an unfrozen backbone cannot reach this point silently.",
            "",
            f"**The vision tower is not loaded.** Vision parameters in the built model: **{row['vision_parameters']}**.",
            "The base is multimodal, but only its `text_config` is instantiated.",
            "",
        ]

    pairs: dict[int, dict[int, dict[str, Any]]] = {}
    for entry in measured:
        pairs.setdefault(entry["batch"], {})[entry["checkpointing"]] = entry
    compared = [batch for batch, settings in sorted(pairs.items()) if len(settings) > 1]
    if compared:
        lines += [
            "**Grad-checkpointing is the largest single lever, and it is on in every run above.** The same",
            "records, the same batch size, one setting apart:",
            "",
            "| model | batch | row tokens | checkpointing | s/step | tokens/s | peak VRAM | MB per row token |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for batch in compared:
            for _, entry in sorted(pairs[batch].items()):
                lines.append(f"| {entry['model']} | {batch} | {entry['row_tokens']:,} | {entry['checkpointing']} | "
                             f"{entry['step_seconds']:.3f} | {entry['tokens_per_second']:,.0f} | "
                             f"{_gb(entry['peak_device_bytes'])} GB | {_mb_per_token(entry):.2f} |")
        lines += [""]
        for batch in compared:
            settings = sorted(pairs[batch])
            first, last = pairs[batch][settings[0]], pairs[batch][settings[-1]]
            delta = abs(last["peak_device_bytes"] - first["peak_device_bytes"]) / max(first["peak_device_bytes"], 1)
            lines.append(f"*Batch {batch}:* the peak falls **{delta * 100:.1f}%** from checkpointing {settings[0]} to "
                         f"{settings[-1]}, and the step costs **{last['step_seconds'] / first['step_seconds']:.2f}×** the time.")
        widest = compared[-1]
        lines += [
            "",
            (f"So the setting is the difference between fitting and not: at batch {widest} it is "
             f"{_gb(pairs[widest][0]['peak_device_bytes'])} GB against {_gb(pairs[widest][1]['peak_device_bytes'])} GB "
             f"on a card with {_gb(_gpu_memory())} GB."),
            f"The recorded probe already had checkpointing on, so this is not what produced its {PROBE['peak_gb']} GB —",
            "but it is the reason every number in the sweep above is cheap.",
            "",
        ]

    if measured:
        by_setting = {setting: [entry for entry in measured if entry["checkpointing"] == setting]
                      for setting in sorted({entry["checkpointing"] for entry in measured})}
        lines += [
            "**What the peak tracks.** Not the records and not the packed length, but the row tokens the hybrid",
            "backbone actually pays for:",
            "",
        ]
        for setting, entries in by_setting.items():
            slopes = [_mb_per_token(entry) for entry in entries]
            smallest, largest = min(entries, key=lambda e: e["row_tokens"]), max(entries, key=lambda e: e["row_tokens"])
            lines.append(f"* checkpointing {setting}: **{min(slopes):.2f}–{max(slopes):.2f} MB per row token**, "
                         f"{smallest['row_tokens']:,} row tokens → {_gb(smallest['peak_device_bytes'])} GB, "
                         f"{largest['row_tokens']:,} → {_gb(largest['peak_device_bytes'])} GB")
        # The probe ran with checkpointing on, so its shape is priced at that setting's slope.
        # An entry taken at the largest batch is the one whose shape is most like a full one.
        best = max(by_setting)
        widest = by_setting[best][-1]
        lines += [
            "",
            "That is activation memory, not optimizer state — optimizer state is two AdamW moments over the",
            "trainable tensors counted above, tens of megabytes, and it is the same either way. The mechanism",
            "behind the growth is visible in the run log: `transformers` prints that `causal_conv1d_fn` fell back",
            "to its reference PyTorch implementation, and the Gated DeltaNet layers run through the same",
            "fused-kernel lookup, so the chunked reference materialises per-layer tensors that checkpointing",
            "would otherwise free eagerly.",
            "",
            (f"The longest batch the smoke suite offers is "
             f"{max(measured, key=lambda e: e['row_tokens'])['row_tokens']:,} row tokens, so the probe's shape is"),
            (f"not reachable from it and its {PROBE['peak_gb']} GB could not be reproduced exactly. A record "
             f"described as"),
            f"\"seq {PROBE['seq']:,}\" is a *packed* length, and the row form repeats the state once per question, so the",
            "same batch is several times that in row tokens. Priced at this machine's slope, the two readings are",
            f"(as a fraction of the probe's {PROBE['peak_gb']} GB):",
            "",
            (f"* {PROBE['seq']:,} row tokens at {_mb_per_token(widest):.2f} MB each → "
             f"**{_forecast(widest, PROBE['seq']):.2f} GB** "
             f"({_forecast(widest, PROBE['seq']) / PROBE['peak_gb']:.0%} of it)"),
            (f"* {4 * PROBE['seq']:,} row tokens ({PROBE['seq']:,} packed at 4 questions per record) → "
             f"**{_forecast(widest, 4 * PROBE['seq']):.2f} GB** "
             f"({_forecast(widest, 4 * PROBE['seq']) / PROBE['peak_gb']:.0%} of it)"),
            "",
            "**Verdict: the 19.6 GB was not an unfrozen backbone.** The backbone is frozen to the tensor and the",
            "vision tower is absent, both measured above; an unfrozen backbone would have shown up as a trainable",
            (f"count in the hundreds of millions instead of the {_probe(rows)['trainable']['count']:,} measured "
             f"({_kinds(_probe(rows)['trainable']['by_kind'])})."),
            "Reading the probe's `seq` as a packed length and pricing the row form it implies closes most of the",
            "gap; the remainder is not explained by anything this command varies - batch size, checkpointing or",
            "the shape of the smoke suite. It is recorded as **unresolved** rather than attributed, and the way to",
            "settle it is a run at the probe's own shape on the real corpus, not a smaller one here.",
            "",
        ]
    return lines


# --------------------------------------------------------------------------- cli


def main(argv: list[str] | None = None) -> int:
    import torch

    parser = argparse.ArgumentParser(prog="sckevtype.train.compute",
                                     description="Measure tokens/s and peak VRAM for the frozen-backbone training step.")
    parser.add_argument("--models", default="0.8b", help="comma-separated registry keys (configs/models.yaml)")
    parser.add_argument("--batches", default="1,2,4", help="comma-separated record counts per forward pass")
    parser.add_argument("--checkpointing", default="0,1", help="comma-separated grad-checkpointing settings")
    parser.add_argument("--suite", default="artifacts/suites/smoke", help="suite whose training partition supplies the records")
    parser.add_argument("--models_yaml", default=None, help="registry to read (default configs/models.yaml)")
    parser.add_argument("--max_state", type=int, default=0, help="state token limit (0 = kev's training default)")
    parser.add_argument("--warmup", type=int, default=6, help="steps timed and discarded before the clock is read")
    parser.add_argument("--steps", type=int, default=3, help="steps timed per combination")
    parser.add_argument("--dtype", choices=["fp32", "bf16"], default="bf16")
    parser.add_argument("--device", choices=["cpu", "mps", "cuda"], default="cuda")
    args = parser.parse_args(argv)
    args.batch_sizes = [int(value) for value in args.batches.split(",") if value]
    args.checkpointing_settings = [int(value) for value in args.checkpointing.split(",") if value]
    if not args.batch_sizes or not args.checkpointing_settings or min(args.warmup, args.steps) < 0:
        print("compute failed: --batches and --checkpointing must be non-empty; --warmup and --steps non-negative",
              file=sys.stderr)
        return 1
    if args.device == "cuda" and not torch.cuda.is_available():
        print("compute failed: --device cuda, but CUDA is not available", file=sys.stderr)
        return 1
    try:
        if not args.max_state:
            # The same number the trainer will be handed, from the same manifest. kev's
            # own default (384) is what sized the first VRAM measurement, on records
            # whose branches need thousands of tokens — it died on `branch too long`
            # rather than reporting an allocation.
            args.max_state = recorded_max_state(suite_budget(args.suite))
        registry = load_registry(args.models_yaml)
        keys = [key.strip() for key in args.models.split(",") if key.strip()]
        unknown = sorted(set(keys) - set(registry))
        if unknown:
            raise ValueError(f"models not in the registry: {unknown}; known: {sorted(registry)}")
        rows = [measure_model(key, registry[key], args, keys) for key in keys]
    except (ValueError, KeyError, FileNotFoundError, ImportError) as error:
        print(f"compute failed: {error}", file=sys.stderr)
        return 1

    lines = header(rows, args) + table(rows) + warmup_note(rows) + anomaly(rows)
    skipped = [row for row in rows if row["status"] != "ok"]
    if skipped:
        lines += ["## Not measured", "", *[f"* `{row['key']}`: {row['status']}." for row in skipped], ""]
    print("\n".join(lines))
    return 0


