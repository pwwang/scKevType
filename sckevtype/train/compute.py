"""The capacity measurement behind ``docs/compute.md``.

    python -m sckevtype.train.compute --models 0.8b --batches 1,2,4 > docs/compute.md

Everything this prints to stdout is the document, so progress and diagnostics go
to stderr and the file can be generated by redirection. Three things make the
numbers in it worth quoting:

**The clock is warm before it is read.** An A5000 idles at a few hundred MHz and
takes a moment to reach its boost clock, so the first training step of a process
is measured in slow motion. Every combination runs ``--warmup`` steps that are
timed and thrown away before ``--steps`` steps are timed, and the cold first step
is reported next to the warm median, so the size of that effect is on the page
rather than in a footnote.

**The memory is the memory of *this* configuration.** The model is built by
:mod:`sckevtype.train.model`, so it is the same text-tower-only, backbone-frozen,
LoRA-attached model a real run trains — and what is trainable is measured rather
than assumed. Peak device memory is reset before each timed step, so a
combination's peak is its own and not the union of everything measured before it.

**The unit is the token the backbone actually sees.** A hybrid backbone takes the
row form: one causal row per question, each repeating the state. Counting
``len(enc["ids"])`` would undercount that by the question count, so tokens here
are summed over rows (:func:`sckevtype.train.train.forward_tokens`).

The data is real: batches come from a suite's training partition, encoded through
the model's own strict encoder, and the batch for each size is chosen
deterministically — the longest rows that fit, so batch sizes nest. Nothing here
synthesises a state or invents a length.
"""

