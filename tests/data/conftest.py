@dataclass
class BuiltCorpus:
    """The smoke corpus, built once and read back from the bytes it wrote.

    Records are parsed out of the JSONL with ``Record.from_kev``, so every test below
    it is testing what a consumer of the corpus sees — not the builder's own objects.
    """

    out: Path
    config: Path
    manifest: dict
    records: list
    lines: dict[str, list[dict]]
    cfg: FilterConfig


@pytest.fixture(scope="session")
def smoke_build(smoke_data, tmp_path_factory) -> BuiltCorpus:
    """Build ``configs/corpus/smoke.yaml`` against freshly generated fixtures."""
    from sckevtype.contracts.freeze import read_json
    from sckevtype.contracts.schema import Record
    from sckevtype.data import build as build_module

    root = Path(__file__).resolve().parents[2]
    out = tmp_path_factory.mktemp("smoke-corpus")
    manifest = build_module.build(root / "configs" / "corpus" / "smoke.yaml", out)
    lines, records = {}, []
    for split in ("train", "calibration", "development", "test"):
        lines[split] = [json.loads(line) for line in (out / f"{split}.jsonl").read_text(encoding="utf-8").splitlines() if line]
        records.extend(Record.from_kev(payload) for payload in lines[split])
    corpus = BuiltCorpus(
        out=out,
        config=root / "configs" / "corpus" / "smoke.yaml",
        manifest=manifest,
        records=records,
        lines=lines,
        cfg=FilterConfig.model_validate(read_json(root / "artifacts" / "v1" / "render_config.json")),
    )
    return corpus
